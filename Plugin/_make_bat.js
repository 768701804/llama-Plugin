'setlocal EnableDelayedExpansion',
'title llama.cpp + Plugins',
'',
':: ==========================================================',
':: 配置',
':: ==========================================================',
'for %%I in ("%~dp0..") do set "ROOT=%%~fI"',
'set "HOST_DIR=%~dp0host"',
'set "MODEL_DIR=%ROOT%@@BS@@models"',
'set "URL=http://127.0.0.1:8080"',
'set "UPSTREAM=http://127.0.0.1:8081"',
'',
':: ==========================================================',
':: 检查',
':: ==========================================================',
'where node >nul 2>&1',
'if errorlevel 1 (',
'    echo.',
'    echo ERROR: 没找到 Node.js，插件宿主需要 Node.js 才能跑。',
'    echo   下载: https://nodejs.org/',
'    echo.',
'    pause',
'    exit /b 1',
')',
'',
'if not exist "%ROOT%@@BS@@llama-server.exe" (',
'    echo.',
'    echo ERROR: llama-server.exe not found.',
'    echo   %ROOT%@@BS@@llama-server.exe',
'    echo.',
'    pause',
'    exit /b 1',
')',
'',
'if not exist "%HOST_DIR%@@BS@@host.js" (',
'    echo.',
'    echo ERROR: host.js not found.',
'    echo   %HOST_DIR%@@BS@@host.js',
'    echo.',
'    pause',
'    exit /b 1',
')',
'',
'if not exist "%MODEL_DIR%@@BS@@*.gguf" (',
'    echo.',
'    echo ERROR: no .gguf model found in',
'    echo   %MODEL_DIR%',
'    echo.',
'    pause',
'    exit /b 1',
')',
'',
':: 已经在跑就直接开浏览器，不再起第二个',
'"%SystemRoot%@@BS@@System32@@BS@@curl.exe" -s -f -o nul --max-time 2 "%URL%/health" >nul 2>&1',
'if not errorlevel 1 (',
'    echo.',
'    echo Server already running - opening browser.',
'    start "" "%URL%"',
'    timeout /t 2 >nul 2>&1',
'    exit /b 0',
')',
'',
':: ==========================================================',
':: 扫描模型',
':: ==========================================================',
'set "COUNT=0"',
'for %%F in ("%MODEL_DIR%@@BS@@*.gguf") do (',
'    set /a COUNT+=1',
'    set "FILE[!COUNT!]=%%~nxF"',
'    set "T=%%~zF"',
'    set "SIZE[!COUNT!]=!T:~0,-6!"',
')',
'',
':MODEL_MENU',
'cls',
'echo ================================================',
'echo          llama.cpp   +   Plugins',
'echo ================================================',
'echo.',
'echo Root  : %ROOT%',
'echo Models: %MODEL_DIR%',
'echo Host  : %HOST_DIR%',
'echo.',
'echo Select Model',
'echo.',
'for /l %%I in (1,1,!COUNT!) do (',
'    echo    %%I. !FILE[%%I]!   ^(!SIZE[%%I]! MB^)',
')',
'echo.',
'echo    0. Exit',
'echo.',
'',
'set "SEL="',
'set /p "SEL=Select: "',
'set "SEL=%SEL: =%"',
'if "%SEL%"=="" goto MODEL_MENU',
'if "%SEL%"=="0" goto END',
'for /f "delims=0123456789" %%A in ("%SEL%") do goto MODEL_MENU',
'if %SEL% LSS 1 goto MODEL_MENU',
'if %SEL% GTR %COUNT% goto MODEL_MENU',
'',
'set "MODEL_FILE=!FILE[%SEL%]!"',
'',
':MODE_MENU',
'cls',
'echo ================================================',
'echo              Reasoning Mode',
'echo ================================================',
'echo.',
'echo Model: %MODEL_FILE%',
'echo.',
'echo 1. Think',
'echo 2. No Think',
'echo.',
'echo 0. Back',
'echo.',
'',
'set "MODE="',
'set /p "MODE=Select: "',
'set "MODE=%MODE: =%"',
'',
'if "%MODE%"=="1" (',
'    set "THINK=1"',
'    set "MODE_NAME=Think"',
'    goto START',
')',
'if "%MODE%"=="2" (',
'    set "THINK=0"',
'    set "MODE_NAME=No Think"',
'    goto START',
')',
'if "%MODE%"=="0" goto MODEL_MENU',
'goto MODE_MENU',
'',
':START',
'cls',
'echo ================================================',
'echo                Starting Host',
'echo ================================================',
'echo.',
'echo Root    : %ROOT%',
'echo Model   : %MODEL_FILE%',
'echo Mode    : %MODE_NAME%',
